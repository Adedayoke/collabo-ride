// Renders the tokens as CSS custom properties for the console (`dist/tokens.css`).
// Light values sit on `:root`, dark values under `prefers-color-scheme: dark`, and both again
// under `[data-theme]` so the console's theme toggle can force either mode.

import { color, type ColorMode } from './color.ts'
import { elevation, hairlineWeb } from './elevation.ts'
import { fontFamilies, localeFontSet, type FontSet } from './fonts.ts'
import { duration, easeOut } from './motion.ts'
import { radius } from './radius.ts'
import { size, spacing, zIndex } from './spacing.ts'
import { type } from './type.ts'

const kebab = (name: string) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)

const familyName: Record<FontSet, string> = { DMSans: 'DM Sans', Inter: 'Inter' }
const fallbackStack = 'system-ui, -apple-system, "Segoe UI", Roboto, sans-serif'

function modeVariables(mode: ColorMode): string[] {
  return [
    ...Object.entries(color[mode]).map(([name, value]) => `--color-${kebab(name)}: ${value};`),
    ...Object.entries(elevation[mode]).map(([name, value]) => `--shadow-${name}: ${value};`),
    `color-scheme: ${mode};`,
  ]
}

function staticVariables(): string[] {
  return [
    ...Object.entries(spacing).map(([name, value]) => `--space-${name}: ${value}px;`),
    ...Object.entries(radius).map(([name, value]) => `--radius-${name}: ${value}px;`),
    ...Object.entries(type).flatMap(([name, step]) => [
      `--font-size-${kebab(name)}: ${step.size}px;`,
      `--line-height-${kebab(name)}: ${step.lineHeight}px;`,
      `--font-weight-${kebab(name)}: ${step.weight};`,
    ]),
    `--font-sans: "${familyName.DMSans}", "${familyName.Inter}", ${fallbackStack};`,
    ...Object.entries(duration).map(([name, value]) => `--duration-${kebab(name)}: ${value}ms;`),
    `--ease-out: cubic-bezier(${easeOut.join(', ')});`,
    ...Object.entries(zIndex).map(([name, value]) => `--z-${kebab(name)}: ${value};`),
    `--hairline: ${hairlineWeb}px;`,
    `--size-touch-target: ${size.touchTarget}px;`,
    ...Object.entries(size.button).map(([name, value]) => `--size-button-${name}: ${value}px;`),
    ...Object.entries(size.icon).map(([name, value]) => `--size-icon-${name}: ${value}px;`),
    ...Object.entries(size.avatar).map(([name, value]) => `--size-avatar-${name}: ${value}px;`),
    `--size-content-max: ${size.contentMaxWidth.console}px;`,
    `--size-dialog-max: ${size.dialogMaxWidth}px;`,
    `--focus-ring-width: ${size.focusRing.width}px;`,
    `--focus-ring-offset: ${size.focusRing.offset}px;`,
  ]
}

const block = (selector: string, lines: string[], indent = '') =>
  `${indent}${selector} {\n${lines.map((line) => `${indent}  ${line}`).join('\n')}\n${indent}}`

/** `@font-face` rules for the woff2 files the console serves from `fontUrl`. */
function fontFaces(fontUrl: string): string[] {
  return Object.entries(fontFamilies).flatMap(([set, faces]) =>
    Object.entries(faces).map(([weight, face]) =>
      block('@font-face', [
        `font-family: "${familyName[set as FontSet]}";`,
        `font-style: normal;`,
        `font-weight: ${weight};`,
        `font-display: swap;`,
        `src: url("${fontUrl}/${face.token}.woff2") format("woff2");`,
      ]),
    ),
  )
}

/** Locales the coverage check moved to Inter get Inter first in the stack. */
function localeFonts(): string[] {
  return Object.entries(localeFontSet)
    .filter(([, set]) => set === 'Inter')
    .map(([locale]) => block(`:lang(${locale})`, [`--font-sans: "${familyName.Inter}", ${fallbackStack};`]))
}

export function renderTokensCss(fontUrl: string): string {
  return [
    '/* Generated by `pnpm ui:tokens` from packages/ui/tokens. Do not edit. */',
    ...fontFaces(fontUrl),
    block(':root', [...staticVariables(), ...modeVariables('light')]),
    `@media (prefers-color-scheme: dark) {\n${block(':root', modeVariables('dark'), '  ')}\n}`,
    block('[data-theme="light"]', modeVariables('light')),
    block('[data-theme="dark"]', modeVariables('dark')),
    ...localeFonts(),
    block('.tabular', ['font-variant-numeric: tabular-nums;', 'font-feature-settings: "tnum";']),
    '',
  ].join('\n\n')
}
